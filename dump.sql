    CONSTRAINT FK_ADMIN_MENTORIAS_VOUCHER FOREIGN KEY (VOUCHER_ID) REFERENCES ADMIN_VOUCHERS(ID) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT CK_ADMIN_MENTORIAS_STATUS CHECK (STATUS IN ('PENDENTE','AGENDADA','EM_ANDAMENTO','CONCLUIDA','EXPIRADA','CANCELADA','NO_SHOW'))
) ENGINE=INNODB COMMENT='Projeção resumida de mentorias';





CREATE TABLE IF NOT EXISTS ADMIN_VOUCHER_MOVIMENTACOES (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    VOUCHER_ID BIGINT UNSIGNED NOT NULL,
    MENTORIA_ID BIGINT UNSIGNED NULL,
    TIPO_MOVIMENTACAO VARCHAR(20) NOT NULL,
    QUANTIDADE INT UNSIGNED NOT NULL,
    SALDO_ANTERIOR INT UNSIGNED NOT NULL,
    SALDO_POSTERIOR INT UNSIGNED NOT NULL,
    REFERENCIA_UUID CHAR(36) NULL COMMENT 'UUID externo idempotente da operação, quando fornecido',
    DATA_MOVIMENTACAO DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_VOUCHER_MOV_REF (REFERENCIA_UUID),
    KEY IX_ADMIN_VOUCHER_MOV_VOUCHER_DATA (VOUCHER_ID, DATA_MOVIMENTACAO),
