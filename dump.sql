    CONSTRAINT CK_ADMIN_VOUCHER_MOV_SALDOS CHECK (SALDO_POSTERIOR <= SALDO_ANTERIOR + QUANTIDADE)
) ENGINE=INNODB COMMENT='Histórico de créditos adicionados, consumidos e estornados';






