-- UberHub Mentorias Admin-service
-- MySQL
-- UUIDs externos são CHAR(36) e não possuem FKs entre serviços
-- Todos os IDs internos são BIGINT UNSIGNED AUTO_INCREMENT

CREATE DATABASE IF NOT EXISTS ADMIN_DB
    CHARACTER SET UTF8MB4
    COLLATE UTF8MB4_0900_AI_CI;
USE ADMIN_DB;



-- Usuários projetados do Auth service.
CREATE TABLE IF NOT EXISTS ADMIN_USUARIOS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    USUARIO_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Auth service',
    NOME VARCHAR(160) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL,
    PERFIL VARCHAR(30) NOT NULL COMMENT 'MENTOR, MENTORADO ou papel administrativo',
    STATUS_ACESSO VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    MOTIVO_SUSPENSAO VARCHAR(500) NULL,
    ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_USUARIOS_UUID (USUARIO_UUID),
    UNIQUE KEY UQ_ADMIN_USUARIOS_EMAIL (EMAIL),
    KEY IX_ADMIN_USUARIOS_STATUS_PERFIL (STATUS_ACESSO, PERFIL),
    CONSTRAINT CK_ADMIN_USUARIOS_STATUS CHECK (STATUS_ACESSO IN ('ATIVO','SUSPENSO','INATIVO')),
    CONSTRAINT CK_ADMIN_USUARIOS_PERFIL CHECK (PERFIL IN ('MENTOR','MENTORADO','ADMIN'))
) ENGINE=INNODB COMMENT='Projeção local de usuários do Auth service';





-- Perfil complementar projetado do Mentor service.
CREATE TABLE IF NOT EXISTS ADMIN_MENTORES (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    MENTOR_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Mentor service',
    USUARIO_ID BIGINT UNSIGNED NULL COMMENT 'Usuário local correspondente, quando disponível',
    BIOGRAFIA TEXT NULL,
    STATUS_APROVACAO VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    VALOR_HORA DECIMAL(10,2) NULL,
    ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_MENTORES_UUID (MENTOR_UUID),
    UNIQUE KEY UQ_ADMIN_MENTORES_USUARIO (USUARIO_ID),
    KEY IX_ADMIN_MENTORES_STATUS (STATUS_APROVACAO),
    CONSTRAINT FK_ADMIN_MENTORES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES ADMIN_USUARIOS(ID) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT CK_ADMIN_MENTORES_APROVACAO CHECK (STATUS_APROVACAO IN ('PENDENTE','APROVADO','REPROVADO','SUSPENSO')),
    CONSTRAINT CK_ADMIN_MENTORES_VALOR CHECK (VALOR_HORA IS NULL OR VALOR_HORA >= 0)
) ENGINE=INNODB COMMENT='Projeção local do perfil de mentores';

CREATE TABLE IF NOT EXISTS ADMIN_TAGS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TAG_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Profile service',
    NOME VARCHAR(120) NOT NULL,
    CATEGORIA VARCHAR(100) NULL,
    STATUS VARCHAR(15) NOT NULL DEFAULT 'ATIVA',
    ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_TAGS_UUID (TAG_UUID),
    UNIQUE KEY UQ_ADMIN_TAGS_NOME_CATEGORIA (NOME, CATEGORIA),
    KEY IX_ADMIN_TAGS_STATUS_CATEGORIA (STATUS, CATEGORIA),
    CONSTRAINT CK_ADMIN_TAGS_STATUS CHECK (STATUS IN ('ATIVA','INATIVA'))
) ENGINE=INNODB COMMENT='Cópia local de tags do Profile service';

CREATE TABLE IF NOT EXISTS ADMIN_MENTOR_TAGS (
    MENTOR_ID BIGINT UNSIGNED NOT NULL,
    TAG_ID BIGINT UNSIGNED NOT NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (MENTOR_ID, TAG_ID),
    KEY IX_ADMIN_MENTOR_TAGS_TAG (TAG_ID),
    CONSTRAINT FK_ADMIN_MENTOR_TAGS_MENTOR FOREIGN KEY (MENTOR_ID) REFERENCES ADMIN_MENTORES(ID) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_ADMIN_MENTOR_TAGS_TAG FOREIGN KEY (TAG_ID) REFERENCES ADMIN_TAGS(ID) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=INNODB COMMENT='Relação local N:N entre mentores e tags';




CREATE TABLE IF NOT EXISTS ADMIN_VOUCHERS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    VOUCHER_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Voucher service',
    CODIGO VARCHAR(64) NOT NULL,
    TIPO VARCHAR(15) NOT NULL COMMENT 'ABERTO ou RESTRITO',
    QUANTIDADE_CREDITOS INT UNSIGNED NOT NULL,
    CREDITOS_DISPONIVEIS INT UNSIGNED NOT NULL,
    STATUS VARCHAR(15) NOT NULL DEFAULT 'ATIVO',
    VALIDADE DATETIME(3) NULL,
    MENTORADO_UUID CHAR(36) NULL COMMENT 'UUID externo do usuário que resgatou',
    USUARIO_ID BIGINT UNSIGNED NULL COMMENT 'Projeção local do mentorado, se sincronizada',
    ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_VOUCHERS_UUID (VOUCHER_UUID),
    UNIQUE KEY UQ_ADMIN_VOUCHERS_CODIGO (CODIGO),
    KEY IX_ADMIN_VOUCHERS_STATUS_VALIDADE (STATUS, VALIDADE),
    KEY IX_ADMIN_VOUCHERS_USUARIO (USUARIO_ID),
    KEY IX_ADMIN_VOUCHERS_MENTORADO_UUID (MENTORADO_UUID),
    CONSTRAINT FK_ADMIN_VOUCHERS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES ADMIN_USUARIOS(ID) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT CK_ADMIN_VOUCHERS_TIPO CHECK (TIPO IN ('ABERTO','RESTRITO')),
    CONSTRAINT CK_ADMIN_VOUCHERS_STATUS CHECK (STATUS IN ('ATIVO','RESGATADO','EXPIRADO','CANCELADO')),
    CONSTRAINT CK_ADMIN_VOUCHERS_SALDO CHECK (CREDITOS_DISPONIVEIS <= QUANTIDADE_CREDITOS)
) ENGINE=INNODB COMMENT='Projeção local de vouchers e saldo corrente';





CREATE TABLE IF NOT EXISTS ADMIN_MENTORIAS (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    MENTORIA_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do Mentorship service',
    MENTORADO_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do usuário mentorado',
    MENTOR_UUID CHAR(36) NOT NULL COMMENT 'UUID externo do mentor',
    MENTORADO_ID BIGINT UNSIGNED NULL COMMENT 'Referência à projeção local do usuário',
    MENTOR_ID BIGINT UNSIGNED NULL COMMENT 'Referência à projeção local do mentor',
    VOUCHER_ID BIGINT UNSIGNED NULL COMMENT 'Voucher local associado, quando conhecido',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    DATA_CRIACAO_ORIGEM DATETIME(3) NOT NULL,
    DATA_AGENDADA DATETIME(3) NULL,
    ORIGEM_ATUALIZADO_EM DATETIME(3) NULL,
    CRIADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    ATUALIZADO_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_ADMIN_MENTORIAS_UUID (MENTORIA_UUID),
    KEY IX_ADMIN_MENTORIAS_MENTORADO_STATUS (MENTORADO_UUID, STATUS),
    KEY IX_ADMIN_MENTORIAS_MENTOR_STATUS (MENTOR_UUID, STATUS),
    KEY IX_ADMIN_MENTORIAS_AGENDADA (DATA_AGENDADA),
    KEY IX_ADMIN_MENTORIAS_MENTORADO_ID (MENTORADO_ID),
    KEY IX_ADMIN_MENTORIAS_MENTOR_ID (MENTOR_ID),
    KEY IX_ADMIN_MENTORIAS_VOUCHER (VOUCHER_ID),
